#!/usr/bin/env bash
# Creates the AWS resources the apps use locally in floci, then writes their ids to .env.aws.
# Safe to re-run: existing resources are reused.
set -euo pipefail
cd "$(dirname "$0")/.."

FLOCI_URL=http://localhost:4566
REGION=us-east-1
BUCKET=petfinder-local-photos
POOL_NAME=petfinder-local
CLIENT_NAME=petfinder-ui
UI_ORIGIN=http://localhost:4200
DEMO_EMAIL=demo@petfinder.local
DEMO_PASSWORD='Petfinder1!'

# floci doesn't verify SigV4, so unsigned requests are enough.
cognito() {
  curl -sf "$FLOCI_URL/" -H "X-Amz-Target: AWSCognitoIdentityProviderService.$1" \
    -H 'Content-Type: application/x-amz-json-1.1' -d "$2"
}

if [ "$(curl -s -o /dev/null -w '%{http_code}' -I "$FLOCI_URL/$BUCKET")" != 200 ]; then
  curl -sf -o /dev/null -X PUT "$FLOCI_URL/$BUCKET"
fi
# The browser uploads photos straight to the bucket with a presigned POST.
curl -sf -o /dev/null -X PUT "$FLOCI_URL/$BUCKET?cors" -H 'Content-Type: application/xml' --data "<CORSConfiguration><CORSRule>
<AllowedOrigin>$UI_ORIGIN</AllowedOrigin><AllowedMethod>POST</AllowedMethod><AllowedMethod>GET</AllowedMethod>
<AllowedHeader>*</AllowedHeader><MaxAgeSeconds>3000</MaxAgeSeconds></CORSRule></CORSConfiguration>"
echo "S3 bucket:    $BUCKET"

pool_id=$(cognito ListUserPools '{"MaxResults":60}' | jq -r --arg n "$POOL_NAME" '.UserPools[] | select(.Name == $n) | .Id' | head -1)
if [ -z "$pool_id" ]; then
  pool_id=$(cognito CreateUserPool "$(jq -nc --arg n "$POOL_NAME" '{
    PoolName: $n, UsernameAttributes: ["email"], AutoVerifiedAttributes: ["email"],
    Policies: {PasswordPolicy: {MinimumLength: 8}}}')" | jq -r .UserPool.Id)
fi
echo "Cognito pool: $pool_id"

client_id=$(cognito ListUserPoolClients "$(jq -nc --arg p "$pool_id" '{UserPoolId: $p, MaxResults: 60}')" \
  | jq -r --arg n "$CLIENT_NAME" '.UserPoolClients[] | select(.ClientName == $n) | .ClientId' | head -1)
if [ -z "$client_id" ]; then
  # Public SPA client: no secret, authorization code flow with PKCE, like the AWS environments will use.
  client_id=$(cognito CreateUserPoolClient "$(jq -nc --arg p "$pool_id" --arg n "$CLIENT_NAME" --arg o "$UI_ORIGIN" '{
    UserPoolId: $p, ClientName: $n, GenerateSecret: false,
    ExplicitAuthFlows: ["ALLOW_USER_SRP_AUTH", "ALLOW_USER_PASSWORD_AUTH", "ALLOW_REFRESH_TOKEN_AUTH"],
    AllowedOAuthFlowsUserPoolClient: true, AllowedOAuthFlows: ["code"],
    AllowedOAuthScopes: ["openid", "email", "profile"], SupportedIdentityProviders: ["COGNITO"],
    CallbackURLs: [($o + "/")], LogoutURLs: [($o + "/")]}')" | jq -r .UserPoolClient.ClientId)
fi
echo "Cognito app:  $client_id"

if ! cognito AdminGetUser "$(jq -nc --arg p "$pool_id" --arg u "$DEMO_EMAIL" '{UserPoolId: $p, Username: $u}')" >/dev/null 2>&1; then
  cognito AdminCreateUser "$(jq -nc --arg p "$pool_id" --arg u "$DEMO_EMAIL" '{
    UserPoolId: $p, Username: $u, MessageAction: "SUPPRESS",
    UserAttributes: [{Name: "email", Value: $u}, {Name: "email_verified", Value: "true"}]}')" >/dev/null
  cognito AdminSetUserPassword "$(jq -nc --arg p "$pool_id" --arg u "$DEMO_EMAIL" --arg pw "$DEMO_PASSWORD" '{
    UserPoolId: $p, Username: $u, Password: $pw, Permanent: true}')" >/dev/null
fi
echo "Demo user:    $DEMO_EMAIL / $DEMO_PASSWORD"

cat > .env.aws <<ENV
# Generated by scripts/setup-aws.sh. Don't edit: re-run the script instead.
AWS_REGION=$REGION
AWS_ENDPOINT_URL=$FLOCI_URL
AWS_ACCESS_KEY_ID=test
AWS_SECRET_ACCESS_KEY=test
PHOTOS_BUCKET=$BUCKET
COGNITO_USER_POOL_ID=$pool_id
COGNITO_CLIENT_ID=$client_id
COGNITO_ISSUER=$FLOCI_URL/$pool_id
ENV
echo "Wrote infrastructure/local/.env.aws"
